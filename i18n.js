const GOODVIEW_LOCALES = {
  en: { name: "English", htmlLang: "en" },
  es: { name: "Español", htmlLang: "es" },
  fr: { name: "Français", htmlLang: "fr" },
  "zh-TW": { name: "繁體中文", htmlLang: "zh-Hant" },
};

const originalText = new WeakMap();
const originalAttributes = new WeakMap();

function goodviewTranslate(value, language = "en") {
  if (!value || language === "en") return value;
  const dictionary = GOODVIEW_TRANSLATIONS[language];
  if (!dictionary) return value;
  const source = value.trim();
  if (!source) return value;
  const leading = value.slice(0, value.indexOf(source));
  const trailing = value.slice(value.indexOf(source) + source.length);
  if (dictionary[source]) return `${leading}${dictionary[source]}${trailing}`;

  const replacements = [
    [/^Open video: (.*)\.$/, "Open video: {title}."],
    [/^Open channel page: (.*)\. Browse its videos\.$/, "Open channel page: {name}. Browse its videos."],
    [/^Open channel: (.*)\. Browse its videos and details\.$/, "Open channel: {name}. Browse its videos and details."],
    [/^Open the featured cottage-garden video on its watch page\.$/, "Open the featured cottage-garden video on its watch page."],
    [/^Search (.*) videos$/, "Search {name} videos"],
    [/^(.*) · (\d+) videos?$/, null],
    [/^Browse (\d+) videos uploaded by this channel\.$/, "Browse {count} videos uploaded by this channel."],
    [/^Browse (\d+) video uploaded by this channel\.$/, "Browse {count} videos uploaded by this channel."],
    [/^(.*)\. Browse (\d+) videos? uploaded by this channel\.$/, null],
    [/^No videos match “(.*)”\. Try a different word\.$/, "No videos match “{query}”. Try a different word."],
    [/^Continue watching: (.*)\.$/, "Continue watching: {title}."],
    [/^More actions for (.*)\.$/, "More actions for {title}."],
    [/^Show your (.*) in the Library\.$/, "Show your {name} in the Library."],
    [/^Open the (.*) channel page and browse its videos\.$/, "Open the {name} channel page and browse its videos."],
    [/^(\d+) videos$/, "{count} videos"],
    [/^(\d+) video$/, "{count} video"],
    [/^Now watching · (.*)$/, null],
  ];
  for (const [pattern, key] of replacements) {
    const match = source.match(pattern);
    if (!match) continue;
    if (key === null) {
      if (pattern.source.startsWith("^(.*) ·")) {
        const countKey = Number(match[2]) === 1 ? "{count} video" : "{count} videos";
        const countText = dictionary[countKey];
        return `${leading}${goodviewTranslate(match[1], language)} · ${countText.replace("{count}", match[2])}${trailing}`;
      }
      if (pattern.source.startsWith("^(.*)")) {
        const countKey = Number(match[2]) === 1
          ? "Browse {count} video uploaded by this channel."
          : "Browse {count} videos uploaded by this channel.";
        const countText = dictionary[countKey];
        const sentenceEnd = language === "zh-TW" ? "。" : ".";
        return `${leading}${goodviewTranslate(match[1], language)}${sentenceEnd} ${countText.replace("{count}", match[2])}${trailing}`;
      }
      return `${leading}${goodviewTranslate("Now watching", language)} · ${goodviewTranslate(match[1], language)}${trailing}`;
    }
    const template = dictionary[key];
    if (template) {
      return `${leading}${template.replace(/\{(\w+)\}/g, (_, token) => {
        const index = { title: 1, name: 1, count: 1, query: 1 }[token];
        const replacement = match[index] ?? "";
        return token === "title" || token === "name"
          ? goodviewTranslate(replacement, language)
          : replacement;
      })}${trailing}`;
    }
  }
  return value;
}

function applyGoodViewLanguage(language, title = document.title) {
  const locale = GOODVIEW_LOCALES[language] || GOODVIEW_LOCALES.en;
  document.documentElement.lang = locale.htmlLang;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    node.nodeValue = goodviewTranslate(originalText.get(node), language);
  }
  const attributes = [
    "aria-description",
    "placeholder",
    "title",
    "aria-label",
  ];
  for (const element of document.body.querySelectorAll("*")) {
    let originals = originalAttributes.get(element);
    if (!originals) {
      originals = {};
      originalAttributes.set(element, originals);
    }
    for (const attribute of attributes) {
      if (!element.hasAttribute(attribute)) continue;
      if (!(attribute in originals)) {
        originals[attribute] = element.getAttribute(attribute);
      }
      element.setAttribute(
        attribute,
        goodviewTranslate(originals[attribute], language),
      );
    }
  }
  const titleSuffix = " – GoodView · v4 – Formatted and split";
  if (title.endsWith(titleSuffix)) {
    document.title = `${goodviewTranslate(
      title.slice(0, -titleSuffix.length),
      language,
    )} – GoodView`;
  } else {
    document.title = goodviewTranslate(title, language);
  }
}
